/* Build one merged, vertex-coloured geometry from a list of boxes: [x,y,z,w,h,d,colour] (min corner + size). */
function voxGeo(boxes,s){
  s=s||S8;
  const P=[],N=[],C=[],I=[]; let n=0;
  for(const b of boxes){
    const x0=b[0]*s,y0=b[1]*s,z0=b[2]*s,x1=x0+b[3]*s,y1=y0+b[4]*s,z1=z0+b[5]*s;
    _col.set(b[6]); const r=_col.r,g=_col.g,bl=_col.b;
    const F=[
      x1,y0,z1, x1,y0,z0, x1,y1,z0, x1,y1,z1,  1,0,0,
      x0,y0,z0, x0,y0,z1, x0,y1,z1, x0,y1,z0, -1,0,0,
      x0,y1,z1, x1,y1,z1, x1,y1,z0, x0,y1,z0,  0,1,0,
      x0,y0,z0, x1,y0,z0, x1,y0,z1, x0,y0,z1,  0,-1,0,
      x0,y0,z1, x1,y0,z1, x1,y1,z1, x0,y1,z1,  0,0,1,
      x1,y0,z0, x0,y0,z0, x0,y1,z0, x1,y1,z0,  0,0,-1];
    for(let f=0;f<6;f++){
      const o=f*15;
      for(let k=0;k<4;k++){ P.push(F[o+k*3],F[o+k*3+1],F[o+k*3+2]); N.push(F[o+12],F[o+13],F[o+14]); C.push(r,g,bl); }
      I.push(n,n+1,n+2,n,n+2,n+3); n+=4;
    }
  }
  const g=new T.BufferGeometry();
  g.setAttribute('position',new T.Float32BufferAttribute(P,3));
  g.setAttribute('normal',new T.Float32BufferAttribute(N,3));
  g.setAttribute('color',new T.Float32BufferAttribute(C,3));
  g.setIndex(I);
  return g;
}
